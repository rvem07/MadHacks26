"""The semantic event model (spec section 9).

One event per tool call or decision. MLflow Tracing (optional) supplies
the low-level spans; these events are our own, higher-level record, and
they are what the UI, the narrator, the flags and the reviewer read.

Fidelity labels (shown in the UI next to every piece of an event):
  observed  - tool calls and the data they actually returned
  reported  - the model's own stated rationale (record_decision)
  inferred  - summaries, flags and proposals generated by our system
The system makes the agent's actions and *stated* reasoning auditable;
it does not claim to reveal the model's internal reasoning.

Example event (an ask_human in the stale-owner demo):
{
  "run_id": "r_8f2c1a", "seq": 9, "event_id": "r_8f2c1a:9",
  "timestamp": "2026-11-14T18:02:11+00:00", "stage": "investigate", "actor": "agent",
  "action_type": "ask_human", "tool": "ask_human",
  "node_ids": ["p_priya", "doc_security_specs"], "edge_ids": ["e_priya_owns_secspec"],
  "focus_node": "p_priya",
  "input": {"person_id": "p_priya", "question": "..."},
  "result": {"question_id": "q_51e0", "status": "waiting"},
  "status": "waiting", "latency_ms": 3,
  "decision": null, "evidence_refs": [],
  "milestone": true, "plain_summary": "Asked Priya Shah, listed as owner of Security specs.",
  "narrator": "template", "config_version": 1, "ontology_version": 1,
  "external_ids": {"gmail_message_id": "dryrun-q_51e0"}, "warnings": [],
  "fidelity": {"input": "observed", "result": "observed", "plain_summary": "inferred"}
}
"""
from __future__ import annotations

from .audit import now_iso
from .toolspecs import ACTION_TYPES

ACTORS = ("agent", "system")  # plus "human:<person_id>" for replies


def fidelity_for(action_type: str, has_decision: bool) -> dict:
    """Which parts of an event are observed / reported / inferred."""
    f = {"input": "observed", "result": "observed", "plain_summary": "inferred"}
    if has_decision:
        f["decision"] = "reported"  # options/chosen/rationale come from the agent itself
    if action_type == "conclude":
        f["result"] = "reported"   # the final answer is the agent's claim, backed by evidence_refs
    return f


def make_event(*, run: dict, seq: int, stage: str, actor: str, action_type: str, tool: str | None,
               node_ids: list[str] | None = None, edge_ids: list[str] | None = None,
               focus_node: str | None = None, input: dict | None = None, result: dict | None = None,
               status: str = "ok", latency_ms: int = 0, decision: dict | None = None,
               evidence_refs: list[str] | None = None, milestone: bool = False,
               external_ids: dict | None = None, warnings: list[str] | None = None) -> dict:
    """Build a complete event dict with every field the spec lists."""
    if action_type not in ACTION_TYPES:
        raise ValueError(f"unknown action_type {action_type}")
    return {
        "run_id": run["run_id"], "seq": seq, "event_id": f"{run['run_id']}:{seq}",
        "timestamp": now_iso(), "stage": stage, "actor": actor,
        "action_type": action_type, "tool": tool,
        "node_ids": node_ids or [], "edge_ids": edge_ids or [], "focus_node": focus_node,
        "input": input or {}, "result": result or {}, "status": status, "latency_ms": latency_ms,
        "decision": decision, "evidence_refs": evidence_refs or [],
        "milestone": milestone,            # set by the tool wrapper, never by a model
        "plain_summary": "", "narrator": "",  # filled by the narrator
        "config_version": run["config_version"], "ontology_version": run["ontology_version"],
        "external_ids": external_ids or {}, "warnings": warnings or [],
        "fidelity": fidelity_for(action_type, decision is not None),
    }
